"""Run the release image as if it were the server executable.

Harnesses that take a server executable (`--binary`) get wrapper(): a shell
script that runs the image with the harness's own arguments, so every
qualification test exercises the image that is shipped:

- the container uses the host network (the harness picks the ports) and the
  caller's user ID, so the files it writes are the caller's;
- the temporary directory (TMPDIR, default /tmp), the checkout and the run
  directory are shared at the same paths, so the paths the harness passes mean
  the same inside; the working directory is kept when it is under one of them
  (else it is /);
- the server settings (SETTINGS: the KMIP_* variables the server reads) set for
  the wrapper are passed to the server, never one the wrapper itself sets;
- the image's health check is off: the harness checks readiness itself;
- podman passes SIGTERM and SIGINT on to the server, which handles both, so a
  harness that stops the wrapper stops the container, and --rm removes it.
  Each container carries the label LABEL=<run>; remove() deletes any that are
  left, such as after a harness killed its wrapper with SIGKILL.

With fips, the server runs in FIPS mode on an emulated FIPS host: RHEL's
libcrypto test switch OPENSSL_FORCE_FIPS_MODE=1 plus KMIP_FIPS=true (the
server's own kernel check cannot be faked). That is not a FIPS validation.
"""
import os
import pathlib
import re
import shlex
import subprocess

ROOT = pathlib.Path(__file__).resolve().parents[1]
LABEL = 'dev.keytend.harness-run'


def run_label(default='harness'):
    """The run whose containers these are: KEYTEND_HARNESS_RUN, which release_candidate.py sets for its steps."""
    return os.environ.get('KEYTEND_HARNESS_RUN') or default


def settings():
    """The KMIP_* environment variables the server reads, from its source."""
    names = set()
    for path in (ROOT/'src').rglob('*.rs'):
        names |= set(re.findall(r'"(KMIP_[A-Z0-9_]+)"', path.read_text()))
    return sorted(names)


def passed(environ, fixed=()):
    """The server settings in `environ` to pass to a container, as -e NAME options, except `fixed`."""
    return [x for name in settings() if name in environ and name not in fixed for x in ('-e', name)]


def wrapper(directory, image, engine='podman', fips=False, run='harness'):
    """Write <directory>/image-server[-fips-emulated].sh for `image` (a tag or image ID); returns its path."""
    directory = pathlib.Path(directory).resolve()
    path = directory/('image-server-fips-emulated.sh' if fips else 'image-server.sh')
    shares = [ROOT] + ([directory] if not directory.is_relative_to(ROOT) else [])
    volumes = ' '.join(f'-v {shlex.quote(f"{p}:{p}")}' for p in shares)
    fixed = {'KMIP_FIPS': 'true', 'OPENSSL_FORCE_FIPS_MODE': '1'} if fips else {}
    names = ' '.join(n for n in settings() if n not in fixed)
    options = ''.join(f'-e {k}={v} ' for k, v in fixed.items())
    within = ' | '.join(f'{shlex.quote(str(p))}/*' for p in shares)
    path.write_text(f'''#!/bin/sh
# Generated by scripts/image_server.py: run the image {image} as if it were the server executable{" in emulated FIPS mode (not a FIPS host)" if fips else ""}.
tmp=${{TMPDIR:-/tmp}}
pass=
for name in {names}; do
  if env | grep -q "^$name="; then pass="$pass -e $name"; fi
done
case "$PWD/" in "$tmp"/* | {within}) workdir=$PWD ;; *) workdir=/ ;; esac
# shellcheck disable=SC2086
exec {engine} run --rm -i --network host --userns keep-id --user "$(id -u):$(id -g)" --label {LABEL}={shlex.quote(run)} \\
  --no-healthcheck -v "$tmp:$tmp" {volumes} --workdir "$workdir" $pass {options}{shlex.quote(image)} "$@"
''')
    path.chmod(0o755)
    return path


def remove(engine='podman', run='harness'):
    """Remove the containers a wrapper of `run` left behind; returns their IDs."""
    left = (subprocess.run([engine, 'ps', '-aq', '--filter', f'label={LABEL}={run}'], capture_output=True, text=True).stdout or '').split()
    if left:
        subprocess.run([engine, 'rm', '-f', *left], capture_output=True)
    return left
