"""Extract tag and operation registries from the pinned OASIS HTML specifications.
Requires beautifulsoup4; downloads stay outside the source tree in .cache/specs.
"""
import json, pathlib, re
from bs4 import BeautifulSoup
from check_license import source_header
versions = ['1.0','1.1','1.2','1.3','1.4','2.0','2.1','3.0']
registry = {}; operations = {}; enums = {}
for version in versions:
    soup = BeautifulSoup(pathlib.Path(f'.cache/specs/{version}.html').read_bytes(), 'html.parser')
    ops = {}
    for table in soup.find_all('table'):
        text = table.get_text(' ', strip=True)
        is_tags = '420001' in text and 'Activation Date' in text
        rows=table.find_all('tr')
        title=re.sub(r'[^A-Za-z0-9]','',rows[0].get_text(' ',strip=True)) if rows else ''
        if title.endswith('Name'): title=title[:-4]
        is_ops = title=='Operation' and '00000001' in text and '0000000A' in text
        if title and not is_tags:
            values={}
            for row in rows:
                cells=[re.sub(r'\s+',' ',c.get_text(' ',strip=True)).strip() for c in row.find_all('td')]
                if len(cells)>=2 and re.fullmatch(r'(?:0[xX])?[0-9A-Fa-f]{8}',cells[1]): values[re.sub(r'[^A-Za-z0-9]','',cells[0])]=int(cells[1],16)
            if values: enums.setdefault(title,{}).update(values)
        if not (is_tags or is_ops): continue
        for row in table.find_all('tr'):
            cells = [re.sub(r'\s+', ' ', c.get_text(' ',strip=True)).strip() for c in row.find_all('td')]
            if len(cells) < 2: continue
            name, value = cells[:2]
            if re.fullmatch(r'(?:0[xX])?[0-9A-Fa-f]{6}' if is_tags else r'(?:0[xX])?[0-9A-Fa-f]{8}', value) and 'Reserved' not in name:
                if is_tags: registry[int(value,16)] = name
                else: ops[f'{int(value,16):08X}'] = name
    assert ops.get('00000001')=='Create' and ops.get('00000003')=='Register' and ops.get('0000000A')=='Get', (version,ops)
    operations[version] = ops
lines=[source_header('src/tags.rs').rstrip(), '', '// Generated by scripts/generate_registry.py from pinned OASIS registries.', '#![allow(dead_code)]']
used=set()
for value,name in sorted(registry.items()):
    ident = re.sub(r'[^A-Za-z0-9]+','_',name).strip('_').upper()
    if ident in used: continue
    used.add(ident)
    lines.append(f'pub const {ident}: u32 = 0x{value:06X};')
lines += ['pub fn tag_name(tag: u32) -> Option<&\'static str> {','    match tag {']
for value,name in sorted(registry.items()): lines.append(f'        0x{value:06X} => Some({json.dumps(name)}),')
lines += ['        _ => None,','    }','}']
pathlib.Path('src/tags.rs').write_text('\n'.join(lines)+'\n')
pathlib.Path('docs/specs/registry.json').write_text(json.dumps({'tags':{re.sub(r'[^A-Za-z0-9]','',name):value for value,name in registry.items()},'enums':enums},indent=2)+'\n')
pathlib.Path('docs/specs/operations.json').write_text(json.dumps(operations,indent=2)+'\n')
print(f'{len(registry)} tags; operation counts:', {v:len(ops) for v,ops in operations.items()})
